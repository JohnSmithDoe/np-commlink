#!/usr/bin/env node
// Regenerates the emoji picker's catalog from Unicode CLDR (via emojibase-data)
// into one committed module per UI language, so the build never needs a network
// and the names can never drift from the glyphs they describe.
//
// Run with `pnpm run emoji:build` after bumping emojibase-data.

import { gzipSync } from 'node:zlib';
import { writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as prettier from 'prettier';

const require = createRequire(import.meta.url);

const OUT_DIR = 'src/app/@shared/util/emoji';
const LANGUAGES = ['de', 'en', 'fr'];

// Our tab ids, keyed by the emojibase group number they collect. The three
// groups left out are deliberate: `component` (2) holds skin-tone modifiers that
// render as nothing on their own, `flags` (9) is 270 country flags no grocery,
// task or tracked activity has ever wanted, and entries with no group at all are
// the bare regional indicators the flags are built from.
const GROUP_BY_EMOJIBASE_ID = {
  0: 'smileys',
  1: 'people',
  3: 'nature',
  4: 'food',
  5: 'travel',
  6: 'activities',
  7: 'objects',
  8: 'symbols',
};

const GROUP_IDS = Object.values(GROUP_BY_EMOJIBASE_ID);

const tokenize = (text) =>
  text
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);

// The CLDR label stays verbatim, because it is what a screen reader announces
// for the cell — lowercasing or tokenizing it would turn "Glas Milch" into an
// aria-label reading "glas milch getränk trinken". Search does not need it
// normalized either: the shared `matcherFor` normalizes both sides.
//
// `tags` carries only the synonyms the label does not already contain. A
// substring matcher finds "milch" in "Glas Milch" on its own, so repeating it
// would be bytes that buy no query — and the app ships this per language.
const encodeEntry = ({ emoji, label, tags }) => ({
  glyph: emoji,
  label,
  tags: [...new Set((tags ?? []).flatMap((tag) => tokenize(tag)))]
    .filter((tag) => !label.toLowerCase().includes(tag))
    .join(' '),
});

const groupEntries = (data) => {
  const groups = Object.fromEntries(GROUP_IDS.map((id) => [id, []]));

  for (const entry of data.toSorted((a, b) => a.order - b.order)) {
    const groupId = GROUP_BY_EMOJIBASE_ID[entry.group];
    if (!groupId || !entry.emoji) continue;
    groups[groupId].push(encodeEntry(entry));
  }

  return groups;
};

const moduleSource = (
  language,
  groups
) => `/* ─── why ─────────────────────────────────────────────────────────
 * GENERATED by scripts/build-emoji-data.mjs — do not edit.
 * Unicode CLDR emoji names and synonyms (${language}), grouped by picker tab.
 * \`tags\` holds only the synonyms the label does not already contain, since
 * the matcher is substring-based. Typed by @shared/util/emoji/emoji.catalog.
 * ───────────────────────────────────────────────────────────────── */
export const EMOJI_DATA_${language.toUpperCase()} = ${JSON.stringify(groups, null, 2)} as const;
`;

mkdirSync(OUT_DIR, { recursive: true });

for (const language of LANGUAGES) {
  const data = require(`emojibase-data/${language}/data.json`);
  const groups = groupEntries(data);
  const path = `${OUT_DIR}/emoji.data.${language}.ts`;
  // Formatted here rather than left to the pre-commit hook: `pnpm run lint`
  // covers all of `src`, so an unformatted generated file is a failed gate, and
  // the artifact is committed — it has to leave this script already clean.
  const source = await prettier.format(moduleSource(language, groups), {
    ...(await prettier.resolveConfig(path)),
    parser: 'typescript',
  });
  writeFileSync(path, source);

  const payload = Buffer.from(JSON.stringify(groups));
  const counts = Object.entries(groups)
    .map(([id, entries]) => `${id} ${entries.length}`)
    .join(' · ');
  console.log(
    `${path}\n  ${counts}\n  payload ${(payload.length / 1024).toFixed(1)}K raw · ${(gzipSync(payload).length / 1024).toFixed(1)}K gzip`
  );
}
